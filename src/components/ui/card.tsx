  React.HTMLAttributes<HTMLHeadingElement>
>(({ className, ...props }, ref) => (
  <h3
    ref={ref}
    className={cn(
      "font-headline text-2xl md:text-3xl font-bold tracking-tight text-content-primary",
      className
    )}
    {...props}
  />
));
CardTitle.displayName = "CardTitle";

